describe("templateDrift：只报不自动清", () => {
  test("未记录指纹（首轮）不告警", () => {
    expect(templateDrift({})).toBeNull()
  })

  test("指纹与真实模板一致时不告警", () => {
    // 用真实模板的指纹当基线（当前部署的模板）
    const current = schemaFingerprint(parseTemplateSchema(loadRealTemplate()))
    expect(templateDrift({ templateFingerprint: current })).toBeNull()
  })

  test("指纹不匹配时告警，且文案给出可执行动作（开新会话）", () => {
    const msg = templateDrift({ templateFingerprint: "0000000000000000" })
    expect(msg).not.toBeNull()
    expect(msg).toContain("模板结构已更换")
    // 必须指向「显式重置」的落点，而不是让业务以为要手工修
    expect(msg).toContain("开新会话")
    expect(msg).toContain("07_需求规格产出")
  })

  test("告警文案不得承诺自动迁移（那会诱使模型声称已搬数据）", () => {
    const msg = templateDrift({ templateFingerprint: "0000000000000000" }) ?? ""
    expect(msg).not.toContain("自动迁移")
    expect(msg).not.toContain("已为你转换")
  })
})

/** 读真实模板（供「指纹一致」用例做基线）。 */
function loadRealTemplate(): string {
  const path = join(import.meta.dir, "..", "..", "..", "docs", "reqdoc-prd-template.md")
  return readFileSync(path, "utf8")
}