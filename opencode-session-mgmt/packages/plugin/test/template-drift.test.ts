/**
 * 换模板检测与政策告警的护栏（待决 1「显式重置」+ 待决 2「回执告警」）。
 *
 * 背景：模板结构已是单一事实源（从 md 解析）。换模板有两种后果：
 * - **改了措辞**：编号未变 → 无影响，不该打扰业务；
 * - **改了结构**（章节重编号、功能点挪章、小节增删）：旧会话的槽位地址在新模板里
 *   可能不存在 → 业务被问已答过的问题，或内容落不进交付件且零告警。
 *
 * 处置是**只报不自动清**（显式重置）：`kb.slots` 是唯一事实源、原地覆盖不留历史，
 * 自动清空等于替业务决定"这轮问答不算数"；跨版本搬地址要判断旧内容在新模板的哪一节算数，
 * 服务端无法校验语义（与导入旧稿同一类问题）。故只提示业务开新会话重走。
 */
